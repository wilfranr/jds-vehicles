-- Consultas representativas del catálogo, el panel y la expiración (F5-03). Las ejecuta scripts/explain-volumen.sh.
SELECT '--- Q1 catálogo: listado (visible, disponibilidad, orden por id desc)' AS consulta;
EXPLAIN SELECT id FROM vehiculos WHERE visible_catalogo = 1 AND disponibilidad IN ('DISPONIBLE','RESERVADO') ORDER BY id DESC LIMIT 12;
SELECT '--- Q2 catálogo: total del listado' AS consulta;
EXPLAIN SELECT COUNT(*) FROM vehiculos WHERE visible_catalogo = 1 AND disponibilidad IN ('DISPONIBLE','RESERVADO');
SELECT '--- Q3 catálogo: ordenado por precio' AS consulta;
EXPLAIN SELECT id FROM vehiculos WHERE visible_catalogo = 1 AND disponibilidad IN ('DISPONIBLE','RESERVADO') AND condicion = 'NUEVO' ORDER BY precio ASC LIMIT 12;
SELECT '--- Q4 panel: reservas activas, más recientes primero' AS consulta;
EXPLAIN SELECT id FROM reservas WHERE estado IN ('PENDIENTE_CONTACTO','EN_NEGOCIACION') ORDER BY fecha_reserva DESC, id DESC LIMIT 20;
SELECT '--- Q5 panel: reservas de un estado, más recientes primero' AS consulta;
EXPLAIN SELECT id FROM reservas WHERE estado = 'CANCELADA' ORDER BY fecha_reserva DESC, id DESC LIMIT 20;
SELECT '--- Q6 expiración: pendientes vencidas' AS consulta;
EXPLAIN SELECT id, vehiculo_id FROM reservas WHERE estado = 'PENDIENTE_CONTACTO' AND fecha_expiracion IS NOT NULL AND fecha_expiracion <= NOW();
SELECT '--- Q7 resumen: por vencer en 24 h' AS consulta;
EXPLAIN SELECT COUNT(*) FROM reservas WHERE estado = 'PENDIENTE_CONTACTO' AND fecha_expiracion >= NOW() AND fecha_expiracion <= NOW() + INTERVAL 24 HOUR;
SELECT '--- Q8 cliente: sus reservas, recientes primero' AS consulta;
EXPLAIN SELECT id FROM reservas WHERE usuario_id = 1000 ORDER BY fecha_reserva DESC, id DESC LIMIT 20;
SELECT '--- Q9 tope por usuario: reservas activas de un usuario' AS consulta;
EXPLAIN SELECT COUNT(*) FROM reservas WHERE usuario_id = 1000 AND estado IN ('PENDIENTE_CONTACTO','EN_NEGOCIACION');
SELECT '--- Q10 vehículo con reserva activa (bloqueos y liberación)' AS consulta;
EXPLAIN SELECT id FROM reservas WHERE vehiculo_id = 1000 AND estado IN ('PENDIENTE_CONTACTO','EN_NEGOCIACION');
SELECT '--- Q11 ventas del periodo y su total' AS consulta;
EXPLAIN SELECT COUNT(*), SUM(precio_final) FROM ventas WHERE fecha_venta >= NOW() - INTERVAL 30 DAY AND fecha_venta < NOW();
SELECT '--- Q12 ventas: página ordenada por fecha' AS consulta;
EXPLAIN SELECT id FROM ventas ORDER BY fecha_venta DESC, id DESC LIMIT 20;
SELECT '--- Q13 usuarios: búsqueda por correo (contiene)' AS consulta;
EXPLAIN SELECT id FROM usuarios WHERE email LIKE '%u4321@%' OR nombre LIKE '%Nombre4321%' OR apellido LIKE '%Apellido4321%' ORDER BY id LIMIT 20;
SELECT '--- Q14 usuarios: activos (resumen)' AS consulta;
EXPLAIN SELECT COUNT(*) FROM usuarios WHERE activo = 1;
SELECT '--- Q15 resumen: vehículos por disponibilidad' AS consulta;
EXPLAIN SELECT disponibilidad, COUNT(*) FROM vehiculos GROUP BY disponibilidad;
SELECT '--- Q16 panel: vehículos filtrados por disponibilidad y visibilidad' AS consulta;
EXPLAIN SELECT id FROM vehiculos WHERE disponibilidad = 'DISPONIBLE' AND visible_catalogo = 0 ORDER BY id DESC LIMIT 20;
